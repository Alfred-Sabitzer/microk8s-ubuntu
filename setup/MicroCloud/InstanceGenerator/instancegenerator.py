"""
instancegenerator.py
Generates LXD instance configuration YAML and start script from templates.
Usage:
    python instancegenerator.py --project=<LXD project> --profile=<LXD profile> --image=<LXD Image Name> --template_dir=<template directory> --name=<instance name>
Prerequisites:
    - Python 3.x
    - Template files in the specified template directory
    - Write permissions in the output directory
"""

import yaml
import os
from datetime import datetime
import sys
import getopt
import base64

def load_template(path):
    if not os.path.isfile(path):
        print(f"Error: Template file not found: {path}", file=sys.stderr)
        sys.exit(2)
    text=""
    with open(path, 'r') as f:
        text+=f.read()
    return text

def load_files(path,template_dir):
    if not os.path.isfile(path):
        print(f"Error: Template file not found: {path}", file=sys.stderr)
        sys.exit(2)
    text=""
    with open(path, 'r') as f:
        for line in f:
            if "content:" in line:
                filename = line.strip().split(":", 1)[1].strip()
                file_path = os.path.join(template_dir, filename)
                if os.path.isfile(file_path):
                    file_data = load_template(file_path)
                    # Encode file_data to base64 and split into multiple lines (max 76 chars per line)
                    file_data = base64.b64encode(file_data.encode()).decode()
                    file_data = '\n          '.join([file_data[i:i+76] for i in range(0, len(file_data), 76)])
                    line = "        content: |\n          " + file_data + "\n"
            text += line
    return text

