def main(argv):
    opts, args = getopt.getopt(argv,"h:o:p:i:d:n",["help","project=","profile=","image=","template_dir=","name="])
    project="default"
    profile="default"
    image="ubuntu"
    template_dir="./templates"
    name_instance="demo"

    for opt, arg in opts:
        if opt in ("-h", "--help"):
            print(__doc__)
            sys.exit()
        elif opt in ("-o", "--project"):
            project = arg
        elif opt in ("-p", "--profile"):
            profile = arg
        elif opt in ("-i", "--image"):
            image = arg
        elif opt in ("-d", "--template_dir"):
            template_dir = arg
        elif opt in ("-n", "--name"):
            name_instance = arg
#
# Convention: all lowercase 
# because of ssh and other tools
#

    project = project.lower()
    profile = profile.lower()
    image = image.lower()
    name_instance = name_instance.lower()

    generate_instance_yaml(project, profile, image, template_dir, name_instance)


if __name__ == "__main__":
    if len(sys.argv) > 2:
        main(sys.argv[1:])
    else:
        print(__doc__)
