"""
instancegenerator.py
Generates LXD instance configuration YAML and start script from templates.
Usage:
    python instancegenerator.py --project=<LXD project> --profile=<LXD profile> --image=<LXD Image Name> --template_dir=<template directory> --name=<instance name>
Prerequisites:
    - Python 3.x
    - Template files in the specified template directory
    - Write permissions in the output directory
"""

import yaml
import os
from datetime import datetime
import sys
import getopt

def load_template(path):
    if not os.path.isfile(path):
        print(f"Error: Template file not found: {path}", file=sys.stderr)
        sys.exit(2)
    text=f"\n"
    with open(path, 'r') as f:
        text+=f.read()
    return text

def generate_instance_yaml(project, profile, image, template_dir, name_instance):
    print(f"Generating instance YAML for '{name_instance}'...")
    try:
        path = os.path.join(template_dir, f"{project}_project.yaml")
        project_data = load_template(path)
        project_data += f"\nname: {name_instance}\n"
        project_data += f'description: "{profile} {image} generated on {datetime.now()}"\n'
        project_data += f'profiles:\n  - {profile}\n'

        path = os.path.join(template_dir, f"{image}_image.yaml")
        image_data = load_template(path)

        path = os.path.join("./", f"{name_instance}_profile_replace.yaml")
        if os.path.isfile(path):
            with open(path, 'r') as f:
                profile_config = f.read()
        else:
            path = os.path.join(template_dir, f"{profile}_profile.yaml")
            profile_config = load_template(path)
            path = os.path.join("./", f"{name_instance}_config.yaml")
            if os.path.isfile(path):
                with open(path, 'r') as f:
                    profile_config += f.read()

        path = os.path.join("./", f"{name_instance}_devices_replace.yaml")
        if os.path.isfile(path):
            with open(path, 'r') as f:
                profile_device = f.read()
        else:
            path = os.path.join(template_dir, f"{profile}_devices.yaml")
            profile_device = load_template(path)
            path = os.path.join("./", f"{name_instance}_devices.yaml")
            if os.path.isfile(path):
                with open(path, 'r') as f:
                    profile_device += f.read()

        path = os.path.join(template_dir, f"{image}_launch.yaml")
        with open(path, 'r') as f:
            launch=f.read()        

        instance_config = (
            "# Generated by instancegenerator at https://github.com/Alfred-Sabitzer/microk8s-ubuntu/tree/main/setup/MicroCloud/InstanceGenerator\n"
            "# Please change accordingly\n"
            + project_data + image_data + profile_config + profile_device
            + "\n# End of file\n"
        )

        print(f"Writing instance YAML to '{name_instance}.yaml'...")
        with open(f"{name_instance}.yaml", 'w') as f:
            f.write(instance_config)

        print(f"Writing start script to '{name_instance}.sh'...")
        start_script = (
            "#!/bin/bash\n"
            "############################################################################################\n"
            f"# Install {name_instance}\n"
            "# https://documentation.ubuntu.com/lxd/latest/howto/instances_create/\n"
            "# Images are from https://images.lxd.canonical.com/\n"
            "# see as well https://documentation.ubuntu.com/lxd/latest/howto/images_manage/\n"
            "# and https://documentation.ubuntu.com/lxd/latest/howto/images_remote/\n"
            "############################################################################################\n"
            "#shopt -o -s errexit # Terminates  the shell script if a command returns an error code.\n"
            "#shopt -o -s xtrace  # Displays each command before it is executed.\n"
            "shopt -o -s nounset  # No Variables without definition\n"
            f"app=\"{name_instance}\"\n"
            "lxc list ${app}\n"
            "lxc delete ${app} --force\n"
            f"lxc init {launch} "+"${app} < ${app}.yaml\n"
            "lxc start ${app}\n"
            "lxc list ${app}\n"
            "echo \"${app} Installed\"\n"
        )
        with open(f"{name_instance}.sh", 'w') as f:
            f.write(start_script)
        print("Generation complete.")
    except Exception as e:
        print(f"Error during generation: {e}", file=sys.stderr)
        sys.exit(3)

def main(argv):
    opts, args = getopt.getopt(argv,"h:o:p:i:d:n",["help","project=","profile=","image=","template_dir=","name="])
    project="default"
    profile="default"
    image="ubuntu"
    template_dir="./templates"
    name_instance="demo"

    for opt, arg in opts:
        if opt in ("-h", "--help"):
            print(__doc__)
            sys.exit()
        elif opt in ("-o", "--project"):
            project = arg
        elif opt in ("-p", "--profile"):
            profile = arg
        elif opt in ("-i", "--image"):
            image = arg
        elif opt in ("-d", "--template_dir"):
            template_dir = arg
        elif opt in ("-n", "--name"):
            name_instance = arg
#
# Convention: all lowercase 
# because of ssh and other tools
#

    project = project.lower()
    profile = profile.lower()
    image = image.lower()
    name_instance = name_instance.lower()

    generate_instance_yaml(project, profile, image, template_dir, name_instance)


if __name__ == "__main__":
    if len(sys.argv) > 2:
        main(sys.argv[1:])
    else:
        print(__doc__)
