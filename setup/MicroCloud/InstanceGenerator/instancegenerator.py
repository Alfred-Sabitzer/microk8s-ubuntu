"""
instancegenerator.py
Generates LXD instance configuration YAML and start script from templates.
Usage:
    python instancegenerator.py --project=<LXD project> --profile=<LXD profile> --image=<LXD Image Name> --type=<minimal or full> --template_dir=<template directory> --name=<instance name>
Prerequisites:
    - Python 3.x
    - Template files in the specified template directory
    - Write permissions in the output directory
"""

import yaml
import os
from datetime import datetime
import sys
import getopt

def load_template(template_dir, name):
    path = os.path.join(template_dir, f"{name}")
    if not os.path.isfile(path):
        print(f"Error: Template file not found: {path}", file=sys.stderr)
        sys.exit(2)
    with open(path, 'r') as f:
        return f.read()

def generate_instance_yaml(project, profile, image, type, template_dir, name_instance):
    print(f"Generating instance YAML for '{name_instance}'...")
    try:
        project_data = load_template(template_dir, f"project_{project}.yaml")
        project_data += f"\nname: {name_instance}\n"
        project_data += f'description: "{profile} {image} {type} generated on {datetime.now()}"\n'

        image_data = load_template(template_dir, f"image_{image}.yaml")
        profile_data = load_template(template_dir, f"profile_{profile}.yaml")
        image_config = load_template(template_dir, f"image_{image}.config")
        profile_config = load_template(template_dir, f"profile_{profile}.config")
        type_data = load_template(template_dir, f"type_{type}.yaml")
        profile_device = load_template(template_dir, f"profile_{profile}.device")
        launch = load_template(template_dir, f"image_{image}.launch")

        instance_config = (
            "# Generated by instancegenerator at https://github.com/Alfred-Sabitzer/microk8s-ubuntu/tree/main/setup/MicroCloud/InstanceGenerator\n#"
            "# Please change accordingly\n"
            + project_data + image_data + profile_data + image_config + profile_config + type_data + profile_device
        )

        print(f"Writing instance YAML to '{name_instance}.yaml'...")
        with open(f"{name_instance}.yaml", 'w') as f:
            f.write(instance_config)

        print(f"Writing start script to '{name_instance}.sh'...")
        start_script = (
            "#!/bin/bash\n"
            "############################################################################################\n"
            "# Install {name_instance}\n"
            "# https://documentation.ubuntu.com/lxd/latest/howto/instances_create/\n"
            "# Images are from https://images.lxd.canonical.com/\n"
            "# see as well https://documentation.ubuntu.com/lxd/latest/howto/images_manage/\n"
            "# and https://documentation.ubuntu.com/lxd/latest/howto/images_remote/\n"
            "############################################################################################\n"
            "shopt -o -s nounset\n"
            f"app=\"{name_instance}\"\n"
            "lxc list\n"
            "lxc delete ${app} --force\n"
            f"lxc init {launch} "+"${app} < ${app}.yaml\n"
            "lxc start ${app}\n"
            "lxc list ${app}\n"
            "echo \"${app} Installed\"\n"
        )
        with open(f"{name_instance}.sh", 'w') as f:
            f.write(start_script)
        print("Generation complete.")
    except Exception as e:
        print(f"Error during generation: {e}", file=sys.stderr)
        sys.exit(3)

def main(argv):
    opts, args = getopt.getopt(argv,"h:o:p:i:t:d:n",["help","project=","profile=","image=","type=","template_dir=","name="])
    project="default"
    profile="default"
    image="ubuntu"
    type="minimal"
    template_dir="./templates"
    name_instance="demo"

    for opt, arg in opts:
        if opt in ("-h", "--help"):
            print(__doc__)
            sys.exit()
        elif opt in ("-o", "--project"):
            project = arg
        elif opt in ("-p", "--profile"):
            profile = arg
        elif opt in ("-i", "--image"):
            image = arg
        elif opt in ("-t", "--type"):
            type = arg
        elif opt in ("-d", "--template_dir"):
            template_dir = arg
        elif opt in ("-n", "--name"):
            name_instance = arg
    generate_instance_yaml(project, profile, image, type, template_dir, name_instance)

if __name__ == "__main__":
    if len(sys.argv) > 2:
        main(sys.argv[1:])
    else:
        print(__doc__)
