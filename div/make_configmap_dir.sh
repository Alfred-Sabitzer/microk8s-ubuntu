#!/usr/bin/env bash
#
# Generate a Kubernetes ConfigMap YAML document from a directory.

set -Eeuo pipefail

usage() {
    cat <<EOF
Usage: $0 <source-directory> <output-file> [configmap-name]

Options:
  -h, --help    Show this help

Examples:
  $0 /etc/myapp ./myapp-config.yaml
  $0 ./config ./myapp-config.yaml my-app-config
EOF
}

die() {
    echo "ERROR: $*" >&2
    exit 1
}

if [[ "${1:-}" == "-h" || "${1:-}" == "--help" ]]; then
    usage
    exit 0
fi
[[ $# -ge 2 && $# -le 3 ]] || { usage >&2; exit 2; }

SOURCE_DIR=$1
OUTPUT_FILE=$2
[[ -d "$SOURCE_DIR" ]] || die "Source is not a directory: $SOURCE_DIR"

if (($# == 3)); then
    NAME=$3
else
    NAME=$(basename "$OUTPUT_FILE")
    NAME=${NAME%.*}
    NAME=${NAME//[^A-Za-z0-9-]/-}
    NAME=${NAME,,}
    NAME="${NAME:-config}-cm"
fi

mapfile -d '' FILES < <(
    find "$SOURCE_DIR" -mindepth 1 -maxdepth 1 -type f -print0 | sort -z
)
((${#FILES[@]} > 0)) || die "Source directory contains no regular files: $SOURCE_DIR"

declare -A SEEN_KEYS=()
declare -a TEXT_FILES=()
declare -a BINARY_FILES=()

for file in "${FILES[@]}"; do
    key=$(basename "$file")
    key=${key//[^A-Za-z0-9_.-]/-}
    [[ -n "$key" ]] || key="file"
    if [[ -n "${SEEN_KEYS[$key]:-}" && "${SEEN_KEYS[$key]}" != "$file" ]]; then
        die "Multiple files produce the ConfigMap key '$key'"
    fi
    SEEN_KEYS[$key]=$file

    if [[ "$file" == *.conf || "$file" == *.ini || "$file" == *.html ||
          "$file" == *.php || "$file" == *.sh || "$file" == *.txt ||
          "$file" == *.json || "$file" == *.yaml || "$file" == *.yml ||
          "$file" == *.xml || "$file" == *.webmanifest ||
          "$file" == */authorized_keys ]]; then
        TEXT_FILES+=("$key|$file")
    else
        BINARY_FILES+=("$key|$file")
    fi
done

OUTPUT_DIR=$(dirname "$OUTPUT_FILE")
mkdir -p "$OUTPUT_DIR"
TMP_FILE=$(mktemp "${OUTPUT_FILE}.tmp.XXXXXX")
trap 'rm -f "$TMP_FILE"' EXIT

{
    echo "---"
    echo "# Generated by $0"
    echo "# Source: $SOURCE_DIR"
    echo "apiVersion: v1"
    echo "kind: ConfigMap"
    echo "metadata:"
    echo "  name: $NAME"

    if ((${#TEXT_FILES[@]} > 0)); then
        echo "data:"
        for entry in "${TEXT_FILES[@]}"; do
            key=${entry%%|*}
            file=${entry#*|}
            echo "  $key: |"
            sed 's/^/    /' "$file"
        done
    fi

    if ((${#BINARY_FILES[@]} > 0)); then
        echo "binaryData:"
        for entry in "${BINARY_FILES[@]}"; do
            key=${entry%%|*}
            file=${entry#*|}
            echo "  $key: $(base64 -w0 "$file")"
        done
    fi
    echo "---"
} >"$TMP_FILE"

mv "$TMP_FILE" "$OUTPUT_FILE"
trap - EXIT
echo "Created $OUTPUT_FILE"
