#!/usr/bin/env bash
#
# Generate a Kubernetes ConfigMap YAML document containing one text file.

set -Eeuo pipefail

usage() {
    cat <<EOF
Usage: $0 <source-file> <output-file> [configmap-name]

Options:
  -h, --help    Show this help

Examples:
  $0 /etc/ssh/sshd_config ./sshd_config.yaml
  $0 ./app.conf ./app.yaml my-app-config
EOF
}

die() {
    echo "ERROR: $*" >&2
    exit 1
}

if [[ "${1:-}" == "-h" || "${1:-}" == "--help" ]]; then
    usage
    exit 0
fi
[[ $# -ge 2 && $# -le 3 ]] || { usage >&2; exit 2; }

INPUT_FILE=$1
OUTPUT_FILE=$2
[[ -f "$INPUT_FILE" ]] || die "Source is not a regular file: $INPUT_FILE"

KEY=$(basename "$INPUT_FILE")
KEY=${KEY//[^A-Za-z0-9_.-]/-}
[[ -n "$KEY" ]] || die "Could not derive a ConfigMap key from: $INPUT_FILE"

if (($# == 3)); then
    NAME=$3
else
    NAME=$(basename "$INPUT_FILE")
    NAME=${NAME%%.*}
    NAME=${NAME//[^A-Za-z0-9-]/-}
    NAME=${NAME,,}
    NAME=${NAME%-}
    NAME=${NAME#-}
    NAME="${NAME:-config}-${KEY//./-}-cm"
fi

OUTPUT_DIR=$(dirname "$OUTPUT_FILE")
mkdir -p "$OUTPUT_DIR"

TMP_FILE=$(mktemp "${OUTPUT_FILE}.tmp.XXXXXX")
trap 'rm -f "$TMP_FILE"' EXIT

{
    echo "---"
    echo "# Generated by $0"
    echo "apiVersion: v1"
    echo "kind: ConfigMap"
    echo "metadata:"
    echo "  name: $NAME"
    echo "data:"
    echo "  $KEY: |"
    sed 's/^/    /' "$INPUT_FILE"
    echo "---"
} >"$TMP_FILE"

mv "$TMP_FILE" "$OUTPUT_FILE"
trap - EXIT
echo "Created $OUTPUT_FILE"
